import { CurrentAirQualityData, AQIScale } from '../types/airQuality';
import { getCategoryForScale } from './aqiCalculations';
import { formatDateTime } from './dateUtils';

export function generateTextReport(
  data: CurrentAirQualityData,
  scale: AQIScale
): string {
  const aqiVal = scale === 'EAQI' ? data.europeanAqi : scale === 'USAQI' ? data.usAqi : data.indAqi;
  const cat = getCategoryForScale(aqiVal, scale);

  return `========================================
BREATHEX AIR QUALITY REPORT
========================================
Location: ${data.location.name}, ${data.location.country}
Coordinates: ${data.location.latitude.toFixed(4)}, ${data.location.longitude.toFixed(4)}
Measurement Time: ${formatDateTime(data.timestamp)}
Data Source: ${data.dataSource}

OVERALL AIR QUALITY
Scale: ${scale}
AQI Value: ${aqiVal ?? 'N/A'}
Status: ${cat.category}
Health Impact: ${cat.healthSummary}

POLLUTANT CONCENTRATIONS
- PM2.5: ${data.pollutants.pm2_5 != null ? `${data.pollutants.pm2_5} µg/m³` : 'N/A'}
- PM10: ${data.pollutants.pm10 != null ? `${data.pollutants.pm10} µg/m³` : 'N/A'}
- Nitrogen Dioxide (NO2): ${data.pollutants.no2 != null ? `${data.pollutants.no2} µg/m³` : 'N/A'}
- Sulphur Dioxide (SO2): ${data.pollutants.so2 != null ? `${data.pollutants.so2} µg/m³` : 'N/A'}
- Ozone (O3): ${data.pollutants.o3 != null ? `${data.pollutants.o3} µg/m³` : 'N/A'}
- Carbon Monoxide (CO): ${data.pollutants.co != null ? `${data.pollutants.co} µg/m³` : 'N/A'}
Dominant Pollutant: ${data.dominantPollutant ?? 'N/A'}

WEATHER CONDITIONS
- Temperature: ${data.weather?.temperature != null ? `${data.weather.temperature}°C` : 'N/A'}
- Humidity: ${data.weather?.humidity != null ? `${data.weather.humidity}%` : 'N/A'}
- Wind: ${data.weather?.windSpeed != null ? `${data.weather.windSpeed} km/h` : 'N/A'}
- Conditions: ${data.weather?.weatherDescription ?? 'N/A'}

HEALTH & ACTIVITY GUIDANCE
- Outdoor Exercise: ${cat.outdoorAdvice}
- Mask Guidance: ${cat.maskAdvice}
- Indoor Ventilation: ${cat.ventilationAdvice}

Report generated by BreatheX Environmental Intelligence Platform.
Disclaimer: For informational and educational purposes only. Does not substitute medical advice.
========================================`;
}

export function downloadJsonReport(data: CurrentAirQualityData, scale: AQIScale): void {
  const text = JSON.stringify({
    platform: 'BreatheX',
    generatedAt: new Date().toISOString(),
    scale,
    data,
  }, null, 2);

  const blob = new Blob([text], { type: 'application/json' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `breathex-report-${data.location.name.toLowerCase()}-${Date.now()}.json`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
